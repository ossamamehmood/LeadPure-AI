export function isRoleAccount(localPart: string): boolean {
  if (!localPart) return false;
  const clean = localPart.toLowerCase().trim();
  if (roleAccounts.has(clean)) return true;
  // Also check common prefix/suffix compounds, e.g. "sales-team", "info.us", "no_reply"
  const base = clean.split(/[._+-]/)[0];
  return roleAccounts.has(base);
}
